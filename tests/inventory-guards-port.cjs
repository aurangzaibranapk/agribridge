const assert = require("assert");
const fs = require("fs");
const read = (f) => fs.readFileSync(require("path").join(__dirname, "..", f), "utf8");
const grn = read("src/actions/agri-grn.ts");
const inv = read("src/actions/inventory.ts");
const intake = read("src/actions/product-intake.ts");
const count = read("src/actions/stock-count.ts");
const trf = read("src/actions/stock-transfer-workflow.ts");
assert.match(grn, /\.eq\("last_number", current\)/, "GRN number race-safe");
assert.match(grn, /Is order ki GRN pehle se hai/, "ek order ki do GRN nahi");
assert.match(grn, /reference_type", "agri_grn"\)/, "GRN stock harkat dobara nahi");
assert.doesNotMatch(grn, /postStockValueChange/, "GRN ko stock gain na likhein");
assert.match(inv, /Stock badalna sirf Owner, Admin ya Warehouse/, "adjustStock role");
assert.match(inv, /manual_adjustment_rollback/, "batch fail par ginti wapas");
assert.match(inv, /\.eq\("status", "pending"\)/, "transfer sirf pending se complete");
assert.match(intake, /Naya maal manzoor karna sirf Owner ya Admin/, "intake admin-only");
assert.match(count, /ek se zyada products se milta hai/, "naam ka dohra milan");
assert.match(count, /purchasePrice <= 0/, "extra item rate > 0");
assert.match(trf, /transaction_type: "transfer_in",\n    category: "Internal Stock Transfer"/, "andaruni transfer income nahi");
