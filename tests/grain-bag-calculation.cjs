assert.equal(rice.total,59500);assert.equal(rice.chungiAmount,100);assert.equal(rice.payable,59400);assert.deepEqual(rice.errors,[]);
const wheat=calc({...input,grainType:'wheat',grossKg:1000});assert.equal(wheat.bags,10);assert.equal(wheat.cutKg,5);
assert.equal(calc({...input,grossKg:60,cutKg:1,cutGrams:250}).cutKg,1.25);
assert.equal(grainKgGrams(1.25),'1 kg 250 gram');assert.equal(grainKgGrams(0.9996),'1 kg 0 gram');
