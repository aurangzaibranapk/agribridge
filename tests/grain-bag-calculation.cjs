assert.equal(partial.fullBags,310);assert.equal(partial.remainingKg,52);assert.equal(partial.cutKg,155.433);assert.equal(partial.chungiAmount,3108.67);
assert.equal(partial.total,1780294.57);assert.equal(partial.payable,1777185.90);
