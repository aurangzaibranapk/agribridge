const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const mod={exports:{}};
new Function('module','exports',ts.transpileModule(fs.readFileSync('src/lib/grain/bag-calculation.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText)(mod,mod.exports);
const {grainBagCalculation:calc,grainBagWeight,grainKgGrams}=mod.exports;
const input={grainType:'rice',grossKg:600,ratePerMaund:4000,cutBasis:'per_bag',cutKg:0,cutGrams:500,chungiBasis:'per_bag',chungiType:'cash',chungiValue:10};
