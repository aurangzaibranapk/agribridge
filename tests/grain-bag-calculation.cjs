assert.equal(calc({...input,chungiBasis:'total',chungiValue:10}).chungiAmount,10,'old total option retained');
assert.equal(calc({...input,cutBasis:'percentage',cutPercentage:2}).cutKg,12,'existing presets retained');
assert.ok(calc({...input,cutGrams:1000}).errors.length);
assert.ok(calc({...input,cutKg:61}).errors.length);
