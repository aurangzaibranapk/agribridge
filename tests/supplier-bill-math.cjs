const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const moduleObject={exports:{}};
const source=ts.transpileModule(fs.readFileSync('src/lib/purchases/bill-math.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
new Function('module','exports',source)(moduleObject,moduleObject.exports);
const {parseBillNumber,purchaseLineTotal,purchaseBillTotals,matchBillProduct,patchBillRow}=moduleObject.exports;
assert.equal(purchaseLineTotal(20,1970),39400);
assert.equal(purchaseLineTotal('20','1,970'),39400);
assert.equal(purchaseLineTotal('20','Rs 1,970'),39400);
assert.equal(purchaseLineTotal('0.1','0.2'),0.02);
assert.equal(purchaseLineTotal('2.5','1.25'),3.13);
assert.equal(parseBillNumber('2038/95'),null,'do not merge unrelated digits');
assert.equal(parseBillNumber('1,97,0'),null);
assert.equal(parseBillNumber('NaN'),null);
assert.equal(parseBillNumber(Infinity),null);
assert.equal(purchaseLineTotal(20,-1970),null);
const imported={row_id:'tilth',product_id:'',quantity:'20',unit_cost:'1970',line_total:4077900};
assert.equal(purchaseBillTotals([imported]).subtotal,39400,'stale total and missing mapping ignored');
const bill=purchaseBillTotals([imported,{quantity:1,unit_cost:470930}],0,0,0);
assert.equal(bill.subtotal,510330);assert.equal(bill.total,510330);assert.equal(bill.due,510330);
const adjusted=purchaseBillTotals([imported],400,100,10000);
assert.equal(adjusted.total,39100);assert.equal(adjusted.due,29100);
assert.ok(purchaseBillTotals([imported],0,0,50000).errors.length);
const edited=patchBillRow([{row_id:'korum',quantity:'21',unit_cost:'2700'},imported],'tilth',{quantity:'2',unit_cost:'100'});
assert.equal(purchaseLineTotal(edited[0].quantity,edited[0].unit_cost),56700);
assert.equal(purchaseLineTotal(edited[1].quantity,edited[1].unit_cost),200);
assert.equal(purchaseBillTotals(edited).subtotal,56900);
assert.equal(patchBillRow(edited.filter(r=>r.row_id!=='tilth'),'tilth',{unit_cost:'9'})[0].unit_cost,'2700','removed row cannot edit its neighbor');
const master=[{id:'a',name:'Tilth',pack_size:'500 ml',product_code:'T001'},{id:'b',name:'Tilth',pack_size:'1 litre',product_code:'T002'}];
assert.equal(matchBillProduct(master,'tilth'),null,'ambiguous names never guess');
assert.equal(matchBillProduct(master,'  TILTH ','500 ml').id,'a');
assert.equal(matchBillProduct(master,'Tilth','250 ml'),null,'wrong pack never falls back');
assert.equal(matchBillProduct(master,'T002').id,'b');
assert.equal(matchBillProduct(master,'New product'),null);
