-- Maker-checker: banane wala apna elaan khud manzoor nahi kar sakta (CHECK + 599 ka trigger/RPC).

create or replace function public.fn_broadcast_is_approver(p_uid uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = p_uid and coalesce(is_active, true) and role in ('owner','super_admin','admin'))
$$;

create or replace function public.fn_broadcast_can_create(p_uid uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = p_uid and coalesce(is_active, true) and role in ('owner','super_admin','admin','manager'))
$$;

create table if not exists public.broadcasts (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity,
  title text not null check (length(btrim(title)) between 3 and 140),
  audience_role text not null check (audience_role in ('farmers','customers','staff','all','custom')),
  audience_spec jsonb not null default '{}'::jsonb,
  channel text not null check (channel in ('whatsapp','sms','both')),
  template_id uuid,
  template_vars jsonb not null default '[]'::jsonb,   -- ["naam","baqi_raqam"] -> {{1}}, {{2}}
  sms_body jsonb not null default '{}'::jsonb,        -- {"en": "...", "rm": "...", "ur": "..."}
  lang text not null default 'rm' check (lang in ('en','rm','ur','pref')),
  schedule_at timestamptz,
  status text not null default 'draft' check (status in ('draft','pending_approval','approved','rejected','cancelled','sending','done')),
  created_by uuid not null default auth.uid(),
  submitted_at timestamptz,
  approved_by uuid,
  approved_at timestamptz,
  rejected_by uuid,
  reject_reason text,
  recipient_count integer not null default 0,
  excluded_count integer not null default 0,
  cost_estimate_usd numeric(12,4),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint broadcasts_no_self_approval check (approved_by is null or approved_by <> created_by),
  constraint broadcasts_no_self_reject check (rejected_by is null or rejected_by <> created_by),
  constraint broadcasts_sms_needs_body check (channel = 'whatsapp' or sms_body <> '{}'::jsonb),
  constraint broadcasts_wa_needs_template check (channel = 'sms' or template_id is not null)
);
create index if not exists broadcasts_status_idx on public.broadcasts (status, schedule_at);

alter table public.broadcasts enable row level security;
drop policy if exists broadcasts_read on public.broadcasts;
create policy broadcasts_read on public.broadcasts for select to authenticated
  using (created_by = auth.uid() or public.fn_broadcast_is_approver(auth.uid()));
-- Sirf "draft" banaya ja sakta hai, apne naam se.
drop policy if exists broadcasts_insert on public.broadcasts;
create policy broadcasts_insert on public.broadcasts for insert to authenticated
  with check (created_by = auth.uid() and status = 'draft' and approved_by is null and rejected_by is null and public.fn_broadcast_can_create(auth.uid()));
-- Draft sirf banane wala badal sakta hai, aur status draft hi rehta hai (aage RPC se).
drop policy if exists broadcasts_update_draft on public.broadcasts;
create policy broadcasts_update_draft on public.broadcasts for update to authenticated
  using (created_by = auth.uid() and status = 'draft')
  with check (created_by = auth.uid() and status = 'draft' and approved_by is null);
-- Koi delete policy nahi: elaan kabhi mitaya nahi jata (cancel hota hai).
revoke all on public.broadcasts from anon;
grant select, insert, update on public.broadcasts to authenticated;
