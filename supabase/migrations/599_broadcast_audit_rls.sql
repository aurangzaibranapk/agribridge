create table if not exists public.broadcast_audit (
  id bigint generated by default as identity primary key,
  broadcast_id uuid references public.broadcasts(id),
  actor uuid,
  action text not null,
  detail jsonb not null default '{}'::jsonb,
  at timestamptz not null default now()
);
create index if not exists broadcast_audit_b_idx on public.broadcast_audit (broadcast_id, at);
alter table public.broadcast_audit enable row level security;
drop policy if exists broadcast_audit_read on public.broadcast_audit;
create policy broadcast_audit_read on public.broadcast_audit for select to authenticated
  using (public.fn_broadcast_is_approver(auth.uid()) or exists (select 1 from public.broadcasts b where b.id = broadcast_id and b.created_by = auth.uid()));
revoke all on public.broadcast_audit from anon, authenticated;
grant select on public.broadcast_audit to authenticated;

-- Audit append-only: update/delete mana (service role ke liye bhi).
create or replace function public.fn_broadcast_audit_immutable() returns trigger language plpgsql as $$
begin raise exception 'broadcast_audit append-only hai'; end $$;
drop trigger if exists trg_broadcast_audit_immutable on public.broadcast_audit;
create trigger trg_broadcast_audit_immutable before update or delete on public.broadcast_audit
  for each row execute function public.fn_broadcast_audit_immutable();

create or replace function public.fn_broadcast_log(p_id uuid, p_action text, p_detail jsonb default '{}'::jsonb)
returns void language sql security definer set search_path = public as $$
  insert into broadcast_audit (broadcast_id, actor, action, detail) values (p_id, auth.uid(), p_action, coalesce(p_detail, '{}'::jsonb))
$$;
revoke all on function public.fn_broadcast_log(uuid, text, jsonb) from public, anon, authenticated;

-- Status ka safar: sirf jaiz qadam. Manzoori par: approver != creator, approver role, aur WhatsApp
-- ke liye Meta-APPROVED template. Yeh trigger service role par bhi lagta hai.
create or replace function public.fn_broadcast_guard() returns trigger language plpgsql security definer set search_path = public as $$
declare ok boolean; tpl text;
begin
  new.updated_at := now();
  if new.created_by is distinct from old.created_by then raise exception 'created_by badla nahi ja sakta'; end if;
  if new.status = old.status then
    if old.status <> 'draft' and (new.audience_spec is distinct from old.audience_spec or new.sms_body is distinct from old.sms_body
       or new.template_id is distinct from old.template_id or new.channel is distinct from old.channel or new.template_vars is distinct from old.template_vars) then
      raise exception 'Submit ke baad paighaam/audience nahi badal sakte; pehle wapas draft karein';
    end if;
    return new;
  end if;
  ok := (old.status, new.status) in (('draft','pending_approval'),('draft','cancelled'),('pending_approval','approved'),('pending_approval','rejected'),
         ('pending_approval','draft'),('pending_approval','cancelled'),('approved','sending'),('approved','cancelled'),('sending','done'),('sending','cancelled'),('rejected','draft'),('done','sending'));
  if not ok then raise exception 'Status % se % nahi ho sakta', old.status, new.status; end if;
  if new.status = 'approved' then
    if new.approved_by is null or new.approved_by = new.created_by then raise exception 'Banane wala apna elaan khud manzoor nahi kar sakta'; end if;
    if not public.fn_broadcast_is_approver(new.approved_by) then raise exception 'Sirf owner/admin manzoor kar sakta hai'; end if;
    if new.channel in ('whatsapp','both') then
      select meta_status into tpl from message_templates where id = new.template_id;
      if tpl is distinct from 'APPROVED' then raise exception 'WhatsApp sirf Meta-APPROVED template se (template: %)', coalesce(tpl,'none'); end if;
    end if;
  end if;
  if new.status = 'rejected' and (new.rejected_by is null or new.rejected_by = new.created_by or coalesce(btrim(new.reject_reason),'') = '') then
    raise exception 'Wapas karne wala koi aur ho aur wajah likhi ho';
  end if;
  if new.status = 'draft' then new.approved_by := null; new.approved_at := null; new.rejected_by := null; end if;
  return new;
end $$;
drop trigger if exists trg_broadcast_guard on public.broadcasts;
create trigger trg_broadcast_guard before update on public.broadcasts for each row execute function public.fn_broadcast_guard();

-- Recipients: sirf "approved/sending" elaan ke bheje ja sakte hain; opt-out wale kabhi "sent" nahi.
create or replace function public.fn_broadcast_recipient_guard() returns trigger language plpgsql security definer set search_path = public as $$
declare st text;
begin
  if new.status in ('sent','delivered','read') and old.status = 'queued' then
    select status into st from broadcasts where id = new.broadcast_id;
    if st not in ('approved','sending','done') then raise exception 'Bina manzoori bhejna mana (status %)', st; end if;
    if not public.fn_messaging_contactable(new.phone) then raise exception 'Yeh number STOP/DND par hai'; end if;
  end if;
  return new;
end $$;
drop trigger if exists trg_broadcast_recipient_guard on public.broadcast_recipients;
create trigger trg_broadcast_recipient_guard before update on public.broadcast_recipients for each row execute function public.fn_broadcast_recipient_guard();

-- Submit: list server banata hai; yahan STOP/DND aur ghalat number nikal kar "freeze".
-- p_recipients: [{party_type, party_id, name, phone, lang, vars}]
create or replace function public.broadcast_submit(p_id uuid, p_recipients jsonb, p_cost_usd numeric default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare b broadcasts; n_ok int; n_skip int;
begin
  select * into b from broadcasts where id = p_id for update;
  if b.id is null then raise exception 'Elaan nahi mila'; end if;
  if b.created_by <> auth.uid() then raise exception 'Sirf banane wala submit kar sakta hai'; end if;
  if b.status <> 'draft' then raise exception 'Sirf draft submit hota hai'; end if;
  if jsonb_typeof(p_recipients) <> 'array' or jsonb_array_length(p_recipients) = 0 then raise exception 'Koi wusool kuninda nahi'; end if;
  delete from broadcast_recipients where broadcast_id = p_id and status in ('queued','skipped_optout');
  insert into broadcast_recipients (broadcast_id, party_type, party_id, name, phone, lang, vars, channel, status)
  select p_id, coalesce(r->>'party_type','custom'), nullif(r->>'party_id','')::uuid, r->>'name', r->>'phone',
         case when r->>'lang' in ('en','rm','ur') then r->>'lang' else 'rm' end, coalesce(r->'vars','{}'::jsonb),
         case when b.channel = 'sms' then 'sms' else 'whatsapp' end,
         case when public.fn_messaging_contactable(r->>'phone') then 'queued' else 'skipped_optout' end
    from jsonb_array_elements(p_recipients) r
   where coalesce(r->>'phone','') ~ '^92[0-9]{10}$'
  on conflict (broadcast_id, phone, channel) do nothing;
  select count(*) filter (where status = 'queued'), count(*) filter (where status = 'skipped_optout') into n_ok, n_skip
    from broadcast_recipients where broadcast_id = p_id;
  if n_ok = 0 then raise exception 'Sab numbers STOP/DND/ghalat hain'; end if;
  update broadcasts set status = 'pending_approval', submitted_at = now(), recipient_count = n_ok,
         excluded_count = jsonb_array_length(p_recipients) - n_ok, cost_estimate_usd = p_cost_usd where id = p_id;
  perform fn_broadcast_log(p_id, 'submitted', jsonb_build_object('recipients', n_ok, 'skipped_optout', n_skip, 'given', jsonb_array_length(p_recipients)));
  return jsonb_build_object('recipients', n_ok, 'excluded', jsonb_array_length(p_recipients) - n_ok);
end $$;

create or replace function public.broadcast_approve(p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare b broadcasts;
begin
  select * into b from broadcasts where id = p_id for update;
  if b.id is null then raise exception 'Elaan nahi mila'; end if;
  if not fn_broadcast_is_approver(auth.uid()) then raise exception 'Sirf owner/admin manzoor kar sakta hai'; end if;
  if b.created_by = auth.uid() then raise exception 'Banane wala apna elaan khud manzoor nahi kar sakta'; end if;
  update broadcasts set status = 'approved', approved_by = auth.uid(), approved_at = now() where id = p_id;
  perform fn_broadcast_log(p_id, 'approved', jsonb_build_object('schedule_at', b.schedule_at));
end $$;

create or replace function public.broadcast_reject(p_id uuid, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
declare b broadcasts;
begin
  select * into b from broadcasts where id = p_id for update;
  if not fn_broadcast_is_approver(auth.uid()) then raise exception 'Sirf owner/admin wapas kar sakta hai'; end if;
  if b.created_by = auth.uid() then raise exception 'Apna elaan khud wapas nahi; cancel karein'; end if;
  update broadcasts set status = 'rejected', rejected_by = auth.uid(), reject_reason = btrim(p_reason) where id = p_id;
  perform fn_broadcast_log(p_id, 'rejected', jsonb_build_object('reason', p_reason));
end $$;

create or replace function public.broadcast_cancel(p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare b broadcasts;
begin
  select * into b from broadcasts where id = p_id for update;
  if b.created_by <> auth.uid() and not fn_broadcast_is_approver(auth.uid()) then raise exception 'Ijazat nahi'; end if;
  update broadcasts set status = 'cancelled' where id = p_id;
  perform fn_broadcast_log(p_id, 'cancelled', '{}'::jsonb);
end $$;

create or replace function public.broadcast_reopen(p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare b broadcasts;
begin
  select * into b from broadcasts where id = p_id for update;
  if b.created_by <> auth.uid() then raise exception 'Sirf banane wala'; end if;
  update broadcasts set status = 'draft' where id = p_id;
  perform fn_broadcast_log(p_id, 'reopened', '{}'::jsonb);
end $$;

-- Approver: nakam WhatsApp numbers ko SMS par dobara (sirf channel 'both').
create or replace function public.broadcast_retry_sms(p_id uuid)
returns integer language plpgsql security definer set search_path = public as $$
declare b broadcasts; n int;
begin
  select * into b from broadcasts where id = p_id;
  if not fn_broadcast_is_approver(auth.uid()) then raise exception 'Sirf owner/admin'; end if;
  if b.channel <> 'both' or b.status not in ('sending','done') then raise exception 'SMS fallback sirf WhatsApp+SMS elaan par'; end if;
  insert into broadcast_recipients (broadcast_id, party_type, party_id, name, phone, lang, vars, channel, status, fallback_of)
  select r.broadcast_id, r.party_type, r.party_id, r.name, r.phone, r.lang, r.vars, 'sms', 'queued', r.id
    from broadcast_recipients r where r.broadcast_id = p_id and r.channel = 'whatsapp' and r.status = 'failed' and fn_messaging_contactable(r.phone)
  on conflict (broadcast_id, phone, channel) do nothing;
  get diagnostics n = row_count;
  if n > 0 and b.status = 'done' then update broadcasts set status = 'sending' where id = p_id; end if;
  perform fn_broadcast_log(p_id, 'retry_sms', jsonb_build_object('added', n));
  return n;
end $$;

-- ---- Worker (service role only) ----
-- Due elaan ke queued numbers uthao; beech mein STOP hua to skip.
create or replace function public.broadcast_claim_batch(p_limit integer)
returns setof public.broadcast_recipients language plpgsql security definer set search_path = public as $$
begin
  update broadcasts set status = 'sending' where status = 'approved' and coalesce(schedule_at, now()) <= now();
  update broadcast_recipients r set status = 'skipped_optout', error = 'opted out before send'
    from broadcasts b where b.id = r.broadcast_id and b.status = 'sending' and r.status = 'queued' and not fn_messaging_contactable(r.phone);
  return query select r.* from broadcast_recipients r join broadcasts b on b.id = r.broadcast_id
    where b.status = 'sending' and r.status = 'queued' order by b.approved_at, r.created_at limit greatest(coalesce(p_limit,0),0);
end $$;

create or replace function public.broadcast_mark(p_recipient uuid, p_status text, p_provider text, p_msg_id text, p_error text default null)
returns void language plpgsql security definer set search_path = public as $$
declare r broadcast_recipients; b broadcasts;
begin
  update broadcast_recipients set status = p_status, provider = p_provider, provider_msg_id = coalesce(p_msg_id, provider_msg_id), error = p_error,
         sent_at = case when p_status = 'sent' then now() else sent_at end,
         failed_at = case when p_status = 'failed' then now() else failed_at end
   where id = p_recipient returning * into r;
  select * into b from broadcasts where id = r.broadcast_id;
  -- WhatsApp nakam + channel both -> SMS fallback
  if p_status = 'failed' and r.channel = 'whatsapp' and b.channel = 'both' and fn_messaging_contactable(r.phone) then
    insert into broadcast_recipients (broadcast_id, party_type, party_id, name, phone, lang, vars, channel, status, fallback_of)
    values (r.broadcast_id, r.party_type, r.party_id, r.name, r.phone, r.lang, r.vars, 'sms', 'queued', r.id) on conflict do nothing;
    -- Der se aaya "failed" (webhook) aur elaan khatam ho chuka: fallback ke liye dobara chalao.
    if found and b.status = 'done' then update broadcasts set status = 'sending' where id = r.broadcast_id; b.status := 'sending'; return; end if;
  end if;
  if not exists (select 1 from broadcast_recipients where broadcast_id = r.broadcast_id and status = 'queued') and b.status = 'sending' then
    update broadcasts set status = 'done' where id = r.broadcast_id;
    insert into broadcast_audit (broadcast_id, actor, action) values (r.broadcast_id, null, 'finished');
  end if;
end $$;

-- Meta / SMS DLR status (webhook).
create or replace function public.broadcast_status_update(p_msg_id text, p_status text, p_error text default null)
returns void language plpgsql security definer set search_path = public as $$
declare r broadcast_recipients;
begin
  if p_status not in ('delivered','read','failed') then return; end if;
  select * into r from broadcast_recipients where provider_msg_id = p_msg_id limit 1;
  if r.id is null then return; end if;
  if p_status = 'failed' then
    perform broadcast_mark(r.id, 'failed', r.provider, p_msg_id, p_error);
  else
    update broadcast_recipients set status = case when status = 'read' then 'read' else p_status end,
           delivered_at = coalesce(delivered_at, now()), read_at = case when p_status = 'read' then now() else read_at end
     where id = r.id and status in ('sent','delivered','read');
  end if;
end $$;

